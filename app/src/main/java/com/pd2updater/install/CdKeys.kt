package com.pd2updater.install

enum class KeyField(val product: Int) { BASE_GAME(24), EXPANSION(25) }

enum class KeyProblem {
    WRONG_LENGTH,
    OLD_KEY_LENGTH,
    INVALID_CHARACTER,
    EXPANSION_KEY_IN_BASE_FIELD,
    BASE_KEY_IN_EXPANSION_FIELD,
    WRONG_PRODUCT,
}

/**
 * Diablo II and Lord of Destruction CD keys, checked as Blizzard's 1.14b
 * installers check them: 26 characters of the alphabet whose decoded product
 * is the field's product. Ported from pd2-launcher `blizzard/keys.rs`.
