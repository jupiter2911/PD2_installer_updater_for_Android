    class Decoded(val product: Int, val public: Int, val value: ByteArray)

    /** Remove dashes and spaces and make upper case. */
    fun normalize(raw: String): String =
        raw.filter { it != '-' && it != ' ' }.map { if (it in 'a'..'z') it - 32 else it }.joinToString("")

    /** What is wrong with a key in this field, or null when it can be installed. */
    fun problem(field: KeyField, raw: String): KeyProblem? {
        val key = normalize(raw)
        when (key.length) {
            KEY_LENGTH -> {}
            OLD_KEY_LENGTH -> return KeyProblem.OLD_KEY_LENGTH
            else -> return KeyProblem.WRONG_LENGTH
        }
        if (!key.all { it in ALPHABET }) return KeyProblem.INVALID_CHARACTER
        return productProblem(field, decode(digits(key)).product)
    }

    internal fun productProblem(field: KeyField, product: Int): KeyProblem? = when {
        product == field.product -> null
        field == KeyField.BASE_GAME && product == KeyField.EXPANSION.product -> KeyProblem.EXPANSION_KEY_IN_BASE_FIELD
        field == KeyField.EXPANSION && product == KeyField.BASE_GAME.product -> KeyProblem.BASE_KEY_IN_EXPANSION_FIELD
        else -> KeyProblem.WRONG_PRODUCT
    }

    internal fun digits(key: String): IntArray = IntArray(key.length) { ALPHABET.indexOf(key[it]) }

    /**
     * Base-5 pairs at a stride into a 120-bit number, through the substitution
     * box, then a bit permutation. token[0] is the most significant word.
     */
    internal fun decode(digits: IntArray): Decoded {
        val base5 = IntArray(52)
        var second = 0x21
        for (digit in digits) {
            val first = (second + 0x7b5) % 52
            second = (first + 0x7b5) % 52
            base5[first] = digit / 5
            base5[second] = digit % 5
        }
        val token = IntArray(4)
        for (digit in base5.reversed()) {
            var carry = digit.toLong()
            for (word in 3 downTo 0) {
                val product = (token[word].toLong() and 0xffffffffL) * 5 + carry
                token[word] = product.toInt()
                carry = product ushr 32
            }
        }
        for (nibble in 29 downTo 0) {
            val row = nibble * 16
            var acc = getNibble(token, nibble)
            for (other in 29 downTo nibble + 1) acc = SBOX[row + (getNibble(token, other) xor SBOX[row + acc])]
            for (other in nibble - 1 downTo 0) acc = SBOX[row + (getNibble(token, other) xor SBOX[row + acc])]
            setNibble(token, nibble, SBOX[row + acc])
        }
        val source = token.copyOf()
        var from = 0
        for (bit in 0 until 120) {
            setBit(token, bit, getBit(source, from))
            from = (from + 11) % 120
        }
        val value = ByteArray(10)
        value[0] = token[1].toByte()
        value[1] = (token[1] ushr 8).toByte()
        for (i in 0 until 4) {
            value[2 + i] = (token[2] ushr (8 * i)).toByte()
            value[6 + i] = (token[3] ushr (8 * i)).toByte()
        }
        return Decoded(token[0] ushr 10, ((token[0] and 0x3ff) shl 16) or (token[1] ushr 16), value)
    }

    private fun getNibble(token: IntArray, nibble: Int): Int =
        (token[3 - (nibble shr 3)] ushr ((nibble and 7) * 4)) and 0xf

    private fun setNibble(token: IntArray, nibble: Int, value: Int) {
        val shift = (nibble and 7) * 4
        val word = 3 - (nibble shr 3)
        token[word] = (token[word] and (0xf shl shift).inv()) or ((value and 0xf) shl shift)
    }

    private fun getBit(token: IntArray, bit: Int): Int = (token[3 - (bit shr 5)] ushr (bit and 31)) and 1

    private fun setBit(token: IntArray, bit: Int, value: Int) {
        val shift = bit and 31
        val word = 3 - (bit shr 5)
        token[word] = (token[word] and (1 shl shift).inv()) or ((value and 1) shl shift)
    }
}
